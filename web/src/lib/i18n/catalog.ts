export type CatalogKey = keyof typeof CORE_ENGLISH_CATALOG;

export const ENGLISH_CATALOG: Record<string, string> = {
  ...CORE_ENGLISH_CATALOG,
};

export interface CatalogLayers {
  locale?: Record<string, string>;
  module?: Record<string, string>;
  core?: Record<string, string>;
}

export function resolveMessage(
  key: string,
  layers: CatalogLayers = {},
): string {
  return (
    layers.locale?.[key] ??
    layers.module?.[key] ??
    layers.core?.[key] ??
    ENGLISH_CATALOG[key] ??
    `⟦${key}⟧`
  );
}

export function translate(key: string, fallback?: string): string {
  return resolveMessage(key, { core: ENGLISH_CATALOG }) === `⟦${key}⟧`
    ? (fallback ?? `⟦${key}⟧`)
    : resolveMessage(key, { core: ENGLISH_CATALOG });
}

export function catalogKeys(): string[] {
  return Object.keys(ENGLISH_CATALOG).sort();
}
